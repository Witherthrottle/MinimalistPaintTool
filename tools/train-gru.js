#!/usr/bin/env node
/* Train the GRU next-tool model offline with the same code the browser uses.

   Real data:      node tools/train-gru.js out.json session1.json session2.json ...
                   (session files = "Export session JSON" / "Export all sessions" from the app)
   Synthetic demo: node tools/train-gru.js --synthetic js/models/gru_default.js
                   (writes the placeholder model shipped with the app; it encodes the hand-made prior,
                   not real behaviour — retrain once you have pilot data)

   Options: --epochs N  --hidden N  --lr X */
'use strict';
const fs = require('fs');
const path = require('path');

global.window = {};
const root = path.join(__dirname, '..', 'js');
for (const f of ['util.js', 'tools-def.js', 'gru.js', 'predictors.js']) {
  // eslint-disable-next-line no-eval
  (0, eval)(fs.readFileSync(path.join(root, f), 'utf8'));
}
const MP = global.window.MP;
const GRU = MP.GRU;

const args = process.argv.slice(2);
const opt = (name, def) => {
  const i = args.indexOf('--' + name);
  if (i < 0) return def;
  const v = args[i + 1];
  args.splice(i, 2);
  return Number(v);
};
const synthetic = args.includes('--synthetic');
if (synthetic) args.splice(args.indexOf('--synthetic'), 1);
const epochs = opt('epochs', synthetic ? 12 : 40);
const hidden = opt('hidden', 24);
const lr = opt('lr', 0.01);
const [out, ...inputs] = args;
if (!out) {
  console.error('usage: node tools/train-gru.js <out.json|out.js> [session.json ...] [--synthetic]');
  process.exit(1);
}

function syntheticSessions(nSessions = 260, len = 70) {
  const ids = MP.TOOL_IDS;
  const pick = (row) => {
    const entries = Object.entries(row);
    let r = Math.random() * entries.reduce((a, [, v]) => a + v, 0);
    for (const [k, v] of entries) { r -= v; if (r <= 0) return k; }
    return entries[entries.length - 1][0];
  };
  const seqs = [];
  for (let s = 0; s < nSessions; s++) {
    let cur = ['pencil', 'brush', 'pen'][s % 3], prev = null;
    let layers = 2, zoom = 1, sel = false;
    const inputs = [], targets = [];
    for (let k = 0; k < len; k++) {
      if (Math.random() < 0.05) layers = Math.min(10, layers + 1);
      zoom = Math.min(8, Math.max(0.25, zoom * Math.exp((Math.random() - 0.5) * 0.4)));
      if (cur === 'lasso' || cur === 'rectselect') sel = true;
      const drawing = MP.TOOLS[cur].cluster === 'draw' || cur === 'eraser';
      const ctx = {
        layerCount: layers, zoom, selectionActive: sel,
        msInTool: (drawing ? 15000 : 3000) * Math.random(),
        strokesInTool: drawing ? Math.floor(Math.random() * 25) : Math.floor(Math.random() * 3),
        lastStrokeLen: drawing ? 50 + Math.random() * 600 : Math.random() * 40,
        lastPressure: 0.3 + Math.random() * 0.6,
        undoRecent: Math.random() < 0.1,
      };
      let next;
      // short "detours" (eyedropper, colour, eraser) usually return to the tool used before them
      if (prev && ['eyedropper', 'colorpicker', 'eraser'].includes(cur) && Math.random() < 0.6 && prev !== cur) next = prev;
      else if (sel && Math.random() < 0.5) next = Math.random() < 0.6 ? 'move' : 'transform';
      else next = pick(MP.PRIOR[cur]);
      if (next === cur) next = pick(MP.PRIOR[cur]);
      if (next === 'move' || next === 'transform' || next === 'brush') sel = sel && Math.random() < 0.5;
      inputs.push({ tool: cur, f: MP.FEATURES.vector(ctx) });
      targets.push(next);
      prev = cur;
      cur = next;
    }
    seqs.push({ inputs, targets });
  }
  return seqs;
}

(async () => {
  let seqs = [];
  if (synthetic) seqs = syntheticSessions();
  for (const f of inputs) {
    const j = JSON.parse(fs.readFileSync(f, 'utf8'));
    const recs = Array.isArray(j) ? j : j.sessions || [j];
    for (const r of recs) seqs.push(...MP.sequencesFromRecord(r));
  }
  if (!seqs.length) { console.error('No tool_change sequences found.'); process.exit(1); }
  console.log(`Training on ${seqs.length} sequences, ${seqs.reduce((a, s) => a + s.inputs.length, 0)} switches`);
  const model = new GRU({ tools: MP.TOOL_IDS, featureNames: MP.FEATURES.names, hidden, meta: { synthetic } });
  await model.train(seqs, {
    epochs, lr,
    onProgress: (r) => console.log(`epoch ${r.epoch}  train ${r.trainLoss.toFixed(3)}  val ${r.valLoss.toFixed(3)}  top1 ${(r.top1 * 100).toFixed(1)}%  top3 ${(r.top3 * 100).toFixed(1)}%`),
  });
  const json = model.toJSON();
  json.meta.label = synthetic ? 'Synthetic placeholder (trained on the built-in prior)' : `Trained on ${inputs.length} file(s)`;
  if (out.endsWith('.js')) {
    fs.writeFileSync(out, '/* Generated by tools/train-gru.js — ' + json.meta.label + ' */\nwindow.MP = window.MP || {};\nwindow.MP.DEFAULT_GRU = ' + JSON.stringify(json) + ';\n');
  } else {
    fs.writeFileSync(out, JSON.stringify(json));
  }
  console.log('Wrote', out);
})();
